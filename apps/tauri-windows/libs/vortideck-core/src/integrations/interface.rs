//! Integration interface
//!
//! This module defines the interface for app integrations.

use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::HashMap;
use std::fmt;

/// Unique identifier for an integration
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct IntegrationId(pub String);

impl fmt::Display for IntegrationId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl IntegrationId {
    pub fn new(id: impl Into<String>) -> Self {
        IntegrationId(id.into())
    }

    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Metadata about an integration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntegrationMetadata {
    pub id: IntegrationId,
    /// The name of the integration
    pub name: String,
    /// The version of the integration
    pub version: String,
    /// A description of the integration
    pub description: String,
    pub author: String,
    pub website: Option<String>,
}

/// Requirements for an integration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntegrationRequirements {
    pub min_version: Option<String>,
    pub max_version: Option<String>,
    pub dependencies: Vec<String>,
}

/// An action that can be performed by an integration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntegrationAction {
    pub name: String,
    pub parameters: HashMap<String, serde_json::Value>,
    /// Correlation and durability metadata generated by the invocation layer.
    /// Legacy callers may omit it; connectors generate a request ID when needed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub execution: Option<IntegrationActionExecution>,
}

#[derive(Debug, Clone, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct IntegrationActionExecution {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub request_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub idempotency_key: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum IntegrationActionStatus {
    Applied,
    TransportAccepted,
    /// Some selected targets accepted the command while others failed before
    /// or during provider dispatch. Per-target evidence is present in outputs.
    Partial,
}

/// Connector evidence returned to the universal invocation boundary. A
/// connector must never report `Applied` unless it observed a correlated
/// provider/host acknowledgement.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IntegrationActionResult {
    pub status: IntegrationActionStatus,
    pub request_id: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub provider_receipt_id: Option<String>,
    #[serde(default)]
    pub outputs: HashMap<String, Value>,
}

/// An event emitted by an integration
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IntegrationEvent {
    pub name: String,
    pub data: Value,
}

/// Integration result
pub type IntegrationResult<T> = Result<T, crate::integrations::traits::IntegrationError>;

#[async_trait::async_trait]
pub trait EventCallback: Send + Sync {
    async fn on_event(&self, event: &str, data: serde_json::Value) -> IntegrationResult<()>;
}
